package mapfile

import (
	"bytes"
	"fmt"
	"io"
	"os"
	"path/filepath"
)

// Fontset aliases used by the SLD converter (sld.FontName) → DejaVu files.
var fontFiles = []struct{ alias, file string }{
	{"sans", "DejaVuSans.ttf"},
	{"sans-bold", "DejaVuSans-Bold.ttf"},
	{"sans-italic", "DejaVuSans-Oblique.ttf"},
	{"sans-bold-italic", "DejaVuSans-BoldOblique.ttf"},
	{"serif", "DejaVuSerif.ttf"},
	{"serif-bold", "DejaVuSerif-Bold.ttf"},
	{"serif-italic", "DejaVuSerif-Italic.ttf"},
	{"serif-bold-italic", "DejaVuSerif-BoldItalic.ttf"},
	{"mono", "DejaVuSansMono.ttf"},
	{"mono-bold", "DejaVuSansMono-Bold.ttf"},
	{"mono-italic", "DejaVuSansMono-Oblique.ttf"},
	{"mono-bold-italic", "DejaVuSansMono-BoldOblique.ttf"},
}

const FontsetRel = "fonts/fontset.txt"

// WriteFonts copies the fonts from srcDir (the msapi image's DejaVu fonts)
// into <mapfileDir>/fonts and writes fontset.txt, so the stock MapServer
// container can use them through the shared volume. Missing fonts fall back
// to the regular face of the same family, then to sans. Returns false when
// no font is available at all (labels are then not drawn).
func WriteFonts(mapfileDir, srcDir string) (bool, error) {
	dst := filepath.Join(mapfileDir, "fonts")
	if err := os.MkdirAll(dst, 0o755); err != nil {
		return false, err
	}
	have := map[string]bool{}
	for _, f := range fontFiles {
		if err := copyIfChanged(filepath.Join(srcDir, f.file), filepath.Join(dst, f.file)); err == nil {
			have[f.file] = true
		}
	}
	if !have["DejaVuSans.ttf"] {
		return false, nil
	}

	var b bytes.Buffer
	b.WriteString("# Generated by msapi. alias  file\n")
	for _, f := range fontFiles {
		file := f.file
		if !have[file] {
			file = "DejaVuSans.ttf"
		}
		fmt.Fprintf(&b, "%-18s %s\n", f.alias, file)
	}
	return true, writeAtomic(filepath.Join(mapfileDir, FontsetRel), b.Bytes(), 0o644)
}

func copyIfChanged(src, dst string) error {
	si, err := os.Stat(src)
	if err != nil {
		return err
	}
	if di, err := os.Stat(dst); err == nil && di.Size() == si.Size() {
		return nil
	}
	in, err := os.Open(src)
	if err != nil {
		return err
	}
	defer in.Close()
	data, err := io.ReadAll(in)
	if err != nil {
		return err
	}
	return writeAtomic(dst, data, 0o644)
}
