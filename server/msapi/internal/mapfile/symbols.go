// Icon is a PNG symbol (Phase 9): referenced in styles as "icon_<name>".
type Icon struct {
	SymbolName string // e.g. "icon_school"
	File       string // path relative to the mapfile dir, e.g. "icons/school.png"
}

// RenderSymbols builds symbols.sym: built-in marks plus one PIXMAP per icon.
func RenderSymbols(icons []Icon) []byte {
	sort.Slice(icons, func(i, j int) bool { return icons[i].SymbolName < icons[j].SymbolName })
	var b bytes.Buffer
	b.WriteString("# Generated by msapi. Do not edit.\nSYMBOLSET\n")
	b.WriteString(builtinSymbols)
	for _, ic := range icons {
		fmt.Fprintf(&b, "SYMBOL\n  NAME %s\n  TYPE PIXMAP\n  IMAGE %s\nEND\n", Quote(ic.SymbolName), Quote(ic.File))
	}
	b.WriteString("END\n")
	return b.Bytes()
}

func SymbolsPath(mapfileDir string) string { return filepath.Join(mapfileDir, "symbols.sym") }

func WriteSymbols(mapfileDir string, icons []Icon) error {
	return writeAtomic(SymbolsPath(mapfileDir), RenderSymbols(icons), 0o644)
}
