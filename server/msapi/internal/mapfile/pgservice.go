package mapfile

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"sort"

	"msapi/internal/model"
)

// PGServicePath is where MapServer finds libpq services (PGSERVICEFILE in
// server/mapserver/mapserver.conf).
func PGServicePath(mapfileDir string) string {
	return filepath.Join(mapfileDir, "secrets", "pg_service.conf")
}

// RenderPGService builds pg_service.conf with one section per PostGIS store,
// so mapfiles use CONNECTION "service=<store>" and never contain passwords.
// Sessions are read-only, same as msapi's own (PLAN.md §5.1).
func RenderPGService(stores map[string]model.PostGISConn) []byte {
	names := make([]string, 0, len(stores))
	for n := range stores {
		names = append(names, n)
	}
	sort.Strings(names)

	var b bytes.Buffer
	b.WriteString("# Generated by msapi. Do not edit: changes are overwritten.\n")
	for _, n := range names {
		c := stores[n]
		fmt.Fprintf(&b, "\n[%s]\n", n)
		fmt.Fprintf(&b, "host=%s\n", c.Host)
		fmt.Fprintf(&b, "port=%d\n", c.Port)
		fmt.Fprintf(&b, "dbname=%s\n", c.Database)
		fmt.Fprintf(&b, "user=%s\n", c.User)
		if c.Password != "" {
			fmt.Fprintf(&b, "password=%s\n", c.Password)
		}
		fmt.Fprintf(&b, "sslmode=%s\n", c.SSLMode)
		b.WriteString("application_name=mapserver\n")
		b.WriteString("options=-c default_transaction_read_only=on\n")
	}
	return b.Bytes()
}

// WritePGService atomically replaces pg_service.conf. The file is 0640 and
// the secrets dir 0750, both with group gid, so MapServer's worker user
// (www-data, gid 33 in the camptocamp image) can read it and nobody else.
// gid < 0 leaves ownership alone.
func WritePGService(mapfileDir string, stores map[string]model.PostGISConn, gid int) error {
	path := PGServicePath(mapfileDir)
	if err := writeAtomic(path, RenderPGService(stores), 0o640); err != nil {
		return err
	}
	if gid < 0 {
		return nil
	}
	dir := filepath.Dir(path)
	if err := os.Chmod(dir, 0o750); err != nil {
		return err
	}
	if err := os.Lchown(dir, -1, gid); err != nil {
		return fmt.Errorf("chown %s: %w", dir, err)
	}
	if err := os.Lchown(path, -1, gid); err != nil {
		return fmt.Errorf("chown %s: %w", path, err)
	}
	return nil
}
